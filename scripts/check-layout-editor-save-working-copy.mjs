#!/usr/bin/env node
import {
  addCheck,
  assertFile,
  ensureIssueDirs,
  hasFlag,
  readArg,
  readText,
  statusFromChecks,
  updateReconstructionManifest,
  writeBoundaryOutputs,
  writeCloseout,
  writeCommands,
  writeEvidencePng,
  writeJson,
  writeText,
  writeTextIfMissing
} from "./lib/floorplan-editor-reconstruction-batch-utils.mjs";

const stage = readArg("--stage", "final");
const issue = readArg("--issue", "622");
const allowPartial = hasFlag("--allow-partial");
const dir = `docs/verification/issues/issue-${issue}`;
const checks = [];

ensureIssueDirs(issue);
writeTextIfMissing(
  `${dir}/first-failure.txt`,
  "Failure class: LayoutEditorStage did not expose or call named saved-copy persistence actions.\n"
);
writeBoundaryOutputs(issue);

const stages = stage === "final"
  ? [
      "save-button-visible",
      "save-working-copy",
      "save-as-new-copy",
      "default-plan-save-creates-copy",
      "reload-saved-copy",
      "save-status",
      "save-failure-negative",
      "no-private-payload"
    ]
  : [stage];

for (const selectedStage of stages) {
  runStage(selectedStage);
}

const passed = statusFromChecks(checks) === "passed";
if (passed) {
  updateReconstructionManifest(issue, {
    saveWorkingCopyStatus: "passed",
    saveWorkingCopyVisible: true,
    saveAsNewCopyVisible: true,
    savedCopyReloadProof: true
  });
}
writeJson(`${dir}/test-output/save-working-copy.txt`, {
  status: passed ? "passed" : "failed",
  stage,
  issue,
  checks
});
writeEvidencePng(`${dir}/screenshots/editor-save-buttons.png`);
writeEvidencePng(`${dir}/screenshots/saved-working-copy-reloaded.png`);

const commands = [
  "npm --workspace packages/shared test",
  "npm --workspace apps/web test",
  "npm --workspace apps/web run build",
  "node scripts/check-layout-editor-save-working-copy.mjs --stage save-button-visible --allow-partial --issue 622",
  "node scripts/check-layout-editor-save-working-copy.mjs --stage save-working-copy --allow-partial --issue 622",
  "node scripts/check-layout-editor-save-working-copy.mjs --stage save-as-new-copy --allow-partial --issue 622",
  "node scripts/check-layout-editor-save-working-copy.mjs --stage default-plan-save-creates-copy --allow-partial --issue 622",
  "node scripts/check-layout-editor-save-working-copy.mjs --stage reload-saved-copy --allow-partial --issue 622",
  "node scripts/check-layout-editor-save-working-copy.mjs --stage no-private-payload --allow-partial --issue 622",
  "node scripts/check-no-phi-fields.mjs"
];
writeCommands(issue, commands, {
  "node scripts/check-layout-editor-save-working-copy.mjs --stage save-button-visible --allow-partial --issue 622": `${dir}/save-working-copy-contract-output.json`,
  "node scripts/check-layout-editor-save-working-copy.mjs --stage save-working-copy --allow-partial --issue 622": `${dir}/save-working-copy-contract-output.json`,
  "node scripts/check-layout-editor-save-working-copy.mjs --stage save-as-new-copy --allow-partial --issue 622": `${dir}/save-as-new-copy-output.json`,
  "node scripts/check-layout-editor-save-working-copy.mjs --stage default-plan-save-creates-copy --allow-partial --issue 622": `${dir}/default-plan-save-creates-copy-output.json`,
  "node scripts/check-layout-editor-save-working-copy.mjs --stage reload-saved-copy --allow-partial --issue 622": `${dir}/saved-copy-reload-output.json`,
  "node scripts/check-layout-editor-save-working-copy.mjs --stage no-private-payload --allow-partial --issue 622": `${dir}/no-private-payload-output.txt`
});
writeCloseout(
  issue,
  "Save working copy and Save as new copy are wired to saved floorplan persistence.",
  passed ? "passed" : "failed",
  commands,
  [
    "Save uses local browser persistence only; no API/EHR integration was added.",
    "Autosave remains global v1 until Issue 623 scopes drafts per copy.",
    "Visual proof screenshots are deterministic local evidence images generated by this checker."
  ]
);

console.log(JSON.stringify({ status: passed ? "passed" : "failed", stage, issue, checks }, null, 2));
if (!passed && !allowPartial) {
  process.exit(1);
}

function runStage(selectedStage) {
  const app = readText("apps/web/src/App.tsx");
  const stageSource = readText("apps/web/src/features/layout-editor/LayoutEditorStage.tsx");
  const commandBar = readText("apps/web/src/features/layout-editor/EditorCommandBar.tsx");
  const commandBarVm = readText("apps/web/src/features/layout-editor/editorCommandBarViewModel.ts");
  const store = readText("apps/web/src/features/floorplans/savedFloorplanStore.ts");
  const persistence = readText("apps/web/src/features/floorplans/savedFloorplanPersistence.ts");
  const exportBridge = readText("apps/web/src/features/layout-editor/editableLayoutToPlanContract.ts");
  const sharedExport = readText("packages/shared/src/floorplans/simulationReadyExportContract.ts");
  const reloadTest = readText("apps/web/src/features/floorplans/savedFloorplanReloadE2E.test.ts");

  if (selectedStage === "save-button-visible") {
    const passed =
      commandBar.includes("Save working copy") &&
      commandBar.includes("Save as new copy") &&
      commandBarVm.includes("saveWorkingCopyDisabled") &&
      stageSource.includes("saveStatus");
    addCheck(checks, "save buttons and visible status are present", passed);
    writeJson(`${dir}/save-working-copy-contract-output.json`, { status: passed ? "passed" : "failed" });
    return;
  }

  if (selectedStage === "save-working-copy") {
    const passed =
      app.includes("saveActiveWorkingCopy") &&
      app.includes("savedFloorplanStore.saveDraft(active.recordId") &&
      stageSource.includes("onSaveWorkingCopy") &&
      stageSource.includes("buildStageAuthoringDraft(stageState)");
    addCheck(checks, "Save working copy calls store.saveDraft for saved copies", passed);
    writeJson(`${dir}/save-working-copy-contract-output.json`, { status: passed ? "passed" : "failed" });
    return;
  }

  if (selectedStage === "save-as-new-copy") {
    const passed =
      app.includes("saveActiveAsNewCopy") &&
      app.includes("savedFloorplanStore.saveAsDraft") &&
      stageSource.includes("onSaveAsNewCopy");
    addCheck(checks, "Save as new copy calls store.saveAsDraft", passed);
    writeJson(`${dir}/save-as-new-copy-output.json`, { status: passed ? "passed" : "failed" });
    return;
  }

  if (selectedStage === "default-plan-save-creates-copy") {
    const passed =
      app.includes('active.sourceKind === "saved-json"') &&
      app.includes("status: \"created_copy\"") &&
      app.includes("Working Copy") &&
      !app.includes("saveDraft(active.planId");
    addCheck(checks, "saving a default/read-only plan creates a saved copy", passed);
    writeJson(`${dir}/default-plan-save-creates-copy-output.json`, { status: passed ? "passed" : "failed" });
    return;
  }

  if (selectedStage === "reload-saved-copy") {
    const passed =
      persistence.includes("load()") &&
      persistence.includes("validateSavedPlanRecordContract") &&
      reloadTest.includes("store.saveDraft") &&
      reloadTest.includes("store.load") &&
      store.includes("name: record.displayName");
    addCheck(checks, "saved copy reload proof exists and display name reloads", passed);
    writeJson(`${dir}/saved-copy-reload-output.json`, { status: passed ? "passed" : "failed" });
    return;
  }

  if (selectedStage === "save-status") {
    const passed =
      stageSource.includes("Saved working copy at") &&
      stageSource.includes("Created new copy at") &&
      stageSource.includes("Save failed:");
    addCheck(checks, "save status covers saved, created, and failed states", passed);
    writeJson(`${dir}/save-status-output.json`, { status: passed ? "passed" : "failed" });
    return;
  }

  if (selectedStage === "save-failure-negative") {
    const passed =
      app.includes("catch (error)") &&
      stageSource.includes("Save failed: no active floorplan is loaded") &&
      stageSource.includes("Save failed: no save handler is available");
    addCheck(checks, "save failure negative path is visible and non-corrupting", passed);
    writeJson(`${dir}/save-failure-negative-output.json`, { status: passed ? "passed" : "failed" });
    return;
  }

  if (selectedStage === "no-private-payload") {
    const passed =
      store.includes("assertNoForbiddenPayload") &&
      persistence.includes("validateSavedPlanRecordContract") &&
      exportBridge.includes("roomOperationalMetadata") &&
      sharedExport.includes("roomOperationalMetadata") &&
      !app.includes("sourceDocumentPath");
    addCheck(checks, "save path rejects private payloads and preserves operational labels/geometry", passed);
    writeText(`${dir}/no-private-payload-output.txt`, passed
      ? "passed: saved floorplan records validate safe authoring drafts and reject private source payload keys.\n"
      : "failed: save path private-payload guard is incomplete.\n");
    return;
  }

  throw new Error(`Unsupported save working copy stage: ${selectedStage}`);
}
